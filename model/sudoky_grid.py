import copy


class SudokyCell:
    def __init__(self, value: int, row: int, col: int):
        self.value = value
        self.row = row
        self.col = col


class SudokyGrid:
    def __init__(self, grid: list[list[int]], initial_mask: list[list[bool]] = None):
        self.grid = grid
        if initial_mask is None:
            self.initial_mask = [[cell != 0 for cell in row] for row in grid]
        else:
            self.initial_mask = initial_mask

    @classmethod
    def from_file(cls, filepath: str) -> "SudokyGrid":
        grid = []
        with open(filepath, "r") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                row = [int(c) if c.isdigit() else 0 for c in line]
                if len(row) == 9:
                    grid.append(row)
        if len(grid) != 9:
            raise ValueError(f"Fichier invalide '{filepath}' : 9 lignes attendues.")
        return cls(grid)

    @classmethod
    def from_dict(cls, grid_dict: dict) -> "SudokyGrid":
        """Crée une grille depuis un dict {(row, col): value}."""
        grid = [[0] * 9 for _ in range(9)]
        for (r, c), v in grid_dict.items():
            grid[r][c] = v
        return cls(grid)

    def display(self, solved_color: str = "\033[96m", title: str = "") -> None:
        _RESET = "\033[0m"
        _BOLD  = "\033[1m"
        if title:
            print(f"\n  {_BOLD}{title}{_RESET}")
        print("  ┌───────┬───────┬───────┐")
        for r in range(9):
            if r in (3, 6):
                print("  ├───────┼───────┼───────┤")
            row_str = "  │"
            for c in range(9):
                if c in (3, 6):
                    row_str += "│"
                val = self.grid[r][c]
                if val == 0:
                    row_str += " · "
                elif self.initial_mask[r][c]:
                    row_str += f" {_BOLD}{val}{_RESET} "
                else:
                    row_str += f" {solved_color}{val}{_RESET} "
            row_str += "│"
            print(row_str)
        print("  └───────┴───────┴───────┘")


